/**
 * @file sound.ts
 * @description Core TypeScript data contracts for "visuan" — an accessibility tool
 * designed to make everyday environments more accessible for Deaf and Hard of Hearing
 * individuals.
 *
 * How this file relates to the app's design & functionality:
 * - Translates raw acoustic events (e.g., sirens, smoke alarms, baby crying, door knocks)
 *   into structured visual notifications (`SoundAlert`) and tactile vibration patterns
 *   (`HapticPattern`).
 * - Defines urgency tiers (`SoundUrgency`) that govern how the UI colors each alert card
 *   (in both Standard mode and Okabe-Ito Colorblind-safe mode) and how intensely the device vibrates.
 */

/**
 * Priority level of a detected sound event.
 * - `urgent`: Immediate safety or distress events (Smoke Alarm, Emergency Siren, Baby Crying).
 *   Rendered in high-contrast Red (or Orange in Colorblind Mode) with intense haptic pulses.
 * - `warning`: Important situational awareness events (Door Knocking, Bicycle Bell, Kitchen Timer).
 *   Rendered in Amber (or Sky Blue in Colorblind Mode) with double-pulse haptics.
 * - `info`: General contextual sounds around the home.
 * - `subtle`: Low-priority background noise or room tone (filtered out from the user feed).
 */
export type SoundUrgency = 'urgent' | 'warning' | 'info' | 'subtle';

/**
 * High-level semantic category of an environmental sound.
 * Used to pair each notification with an intuitive, recognizable icon in the UI.
 */
export type SoundType =
  | 'safety'
  | 'hazard'
  | 'appliance'
  | 'biological'
  | 'animal'
  | 'social'
  | 'ambient'
  | 'warning'
  | 'human_voice';

/**
 * Estimated spatial orientation of the sound source relative to the user's microphone.
 * Computed by comparing left vs. right stereo channel energy when a stereo microphone is available.
 */
export type DirectionCue =
  | 'left'
  | 'center'
  | 'right'
  | 'behind'
  | 'omni'
  | 'approaching';

/**
 * Named tactile vibration rhythms passed to the browser's `navigator.vibrate()` API.
 * Distinct rhythmic patterns allow Deaf and Hard of Hearing users to distinguish
 * an emergency siren (`staccato_emergency`) from a door knock (`double_pulse`) or
 * infant cry (`heartbeat`) by feel alone.
 */
export type HapticPattern =
  | 'staccato_emergency'
  | 'double_pulse'
  | 'gentle_thrum'
  | 'rapid_tap'
  | 'heartbeat';

/**
 * Color vision deficiency modes supported by the design system.
 */
export type ColorBlindMode =
  | 'standard'
  | 'protanopia' // Red-Green color blindness
  | 'tritanopia' // Blue-Yellow color blindness
  | 'monochrome'; // High Contrast Black & White

/**
 * Controls which urgency tiers trigger physical phone vibrations.
 */
export type HapticSensitivity = 'off' | 'emergency_only' | 'low' | 'medium' | 'high';

/**
 * User-configurable microphone sensitivity level.
 * Adjusts both the software pre-amplifier gain (`GainNode`) and the decibel/transient
 * gating thresholds in `audioClassifier.ts`.
 * - `high`: Boosts quiet or distant sounds (2.8x gain, 27 dB gate).
 * - `medium`: Balanced everyday room detection (1.85x gain, 31 dB gate).
 * - `low`: Only triggers on loud, nearby sounds (1.15x gain, 38 dB gate).
 */
export type MicSensitivity = 'high' | 'medium' | 'low';

/**
 * Represents a single classified sound event displayed in the real-time Notifications feed.
 * Returned by the Gemini multimodal audio classifier (`/api/classify-audio` or `/api/live`)
 * or generated by the built-in Sound Tester.
 */
export interface SoundAlert {
  /** Unique identifier used as a React list key and for deduplication */
  id: string;
  /** Unix epoch timestamp (ms) when the sound was detected */
  timestamp: number;
  /** Human-readable title shown on the notification card (e.g., "Smoke Alarm", "Door Knocking") */
  sound_name: string;
  /** Semantic category used for icon selection */
  sound_type: SoundType;
  /** Urgency tier that drives visual badge color and vibration intensity */
  urgency: SoundUrgency;
  /** Plain-language explanation of the sound pattern for the user */
  description: string;
  /** Spatial direction estimate ('left' | 'center' | 'right') */
  direction_cue: DirectionCue;
  /** Classifier confidence score from 0.0 (uncertain) to 1.0 (certain) */
  confidence: number;
  /** Approximate Sound Pressure Level (SPL) in dB at the moment of capture */
  decibels?: number;
  /** Tactile vibration rhythm triggered when this alert arrives */
  haptic_pattern: HapticPattern;
  /** Optional custom accent color override */
  visual_color?: string;
}

/**
 * Metadata for synthetic test sounds in the "Test Sounds" modal.
 */
export interface SoundPreset {
  id: string;
  name: string;
  category: SoundType;
  urgency: SoundUrgency;
  iconName: string;
  description: string;
  direction: DirectionCue;
  hapticPattern: HapticPattern;
  frequencyHint: string;
}

/**
 * User preferences for visual and tactile accessibility.
 */
export interface AccessibilitySettings {
  colorBlindMode: ColorBlindMode;
  hapticSensitivity: HapticSensitivity;
  largeText: boolean;
  screenFlashEnabled: boolean;
  backgroundNotifications: boolean;
  showDecibelMeter: boolean;
  autoDismissHudSeconds: number; // 0 for sticky
}
